import { ProjectSchema, type Project } from '@ill/core-schemas/project';
import { createDraft } from '@ill/core-schemas/workspace';
import { seedProducts } from './seeds';

export function demoProject(base = createDraft()): Project {
  const catalog = (id: string) => seedProducts.find((p) => p.id === id)!;
  const equipment = (
    id: string,
    tag: string,
    catalogId: string,
    fedFrom: string,
    feedLengthFt: number,
    location: string,
  ) => ({
    id,
    tag,
    catalogId,
    category: catalog(catalogId).category,
    qty: 1,
    fedFrom: { ref: fedFrom, ...(fedFrom.startsWith('PS-') ? { port: 'OUT1' } : {}) },
    feedLengthFt,
    location,
    enclosure: location,
    env: 'raceway',
  });
  const tape = (
    id: string,
    typeTag: string,
    catalogId: string,
    lengthFt: number,
    ref: string,
    port: string,
    zone: string,
  ) => ({
    id,
    typeTag,
    zone,
    catalogId,
    lengthFt,
    fedFrom: { ref, port },
    homeRunLengthFt: 20,
    feedMethod: 'end',
    env: 'riser',
  });
  return ProjectSchema.parse({
    ...base,
    meta: {
      ...base.meta,
      name: 'EXAMPLE · Gallery lighting riser',
      number: 'EX-001',
      client: 'Example design review',
      designer: 'EXAMPLE',
      stamp: 'NOT FOR CONSTRUCTION',
    },
    sources: [
      {
        id: 'src-1',
        tag: 'LP-1/12',
        panel: 'LP-1',
        circuit: '12',
        voltage: 120,
        phase: '1PH',
        breakerA: 20,
        poles: 1,
        switching: 'none',
      },
      {
        id: 'src-2',
        tag: 'LP-1/14',
        panel: 'LP-1',
        circuit: '14',
        voltage: 120,
        phase: '1PH',
        breakerA: 20,
        poles: 1,
        switching: 'none',
      },
    ],
    equipment: [
      equipment('ps-1', 'PS-1', 'psu-24v-96w', 'LP-1/12', 35, 'Cabinet A'),
      equipment('ps-2', 'PS-2', 'psu-24v-96w', 'LP-1/12', 4, 'Cabinet A'),
      equipment('ps-3', 'PS-3', 'psu-24v-96w', 'LP-1/14', 28, 'Cabinet B'),
      {
        ...equipment('dec-1', 'DEC-1', 'decoder-4ch', 'PS-1', 4, 'Cabinet A'),
        env: 'riser',
        controlFrom: { ref: 'CON-1', port: 'DATA-OUT' },
        controlLengthFt: 50,
        chainOrder: 1,
        dmx: { universe: 1, startAddress: 'auto', terminatorPresent: false },
      },
      {
        ...equipment('dec-2', 'DEC-2', 'decoder-4ch', 'PS-2', 4, 'Cabinet A'),
        env: 'riser',
        controlFrom: { ref: 'DEC-1' },
        controlLengthFt: 5,
        chainOrder: 2,
        dmx: { universe: 1, startAddress: 'auto', terminatorPresent: true },
      },
      {
        ...equipment('con-1', 'CON-1', 'dmx-controller', 'PS-3', 20, 'Control desk'),
        env: 'riser',
      },
    ],
    loads: [
      tape('load-1', 'T1', 'tape-rgbw', 12, 'DEC-1', 'CH1-4', 'Gallery cove'),
      tape('load-2', 'T2', 'tape-tw', 10, 'DEC-2', 'CH1-2', 'West wall'),
      tape('load-3', 'T3', 'tape-white', 8, 'PS-3', 'OUT1', 'Entry'),
      tape('load-4', 'T3', 'tape-white', 8, 'PS-3', 'OUT1', 'Reception'),
      {
        id: 'load-5',
        typeTag: 'D1',
        zone: 'Gallery',
        catalogId: 'downlight-line',
        qty: 4,
        fedFrom: { ref: 'LP-1/12' },
        homeRunLengthFt: 30,
        interFixtureLengthFt: 6,
        feedMethod: 'end',
        env: 'raceway',
      },
      {
        id: 'load-6',
        typeTag: 'D1',
        zone: 'Entry',
        catalogId: 'downlight-line',
        qty: 2,
        fedFrom: { ref: 'LP-1/14' },
        homeRunLengthFt: 25,
        interFixtureLengthFt: 5,
        feedMethod: 'end',
        env: 'raceway',
      },
    ],
    controlLinks: [],
    wireOverrides: {},
    layoutOverrides: {},
    wireTagMap: {},
  });
}
