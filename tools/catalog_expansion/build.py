"""Build the catalog expansion: version 2 catalogs for products the site is missing.

    python -m tools.catalog_expansion.build --snapshot <fetch_live dir> \\
        --price-list ilLumenate_Price_List_10-2026.xlsx --out tools/catalog_expansion/catalogs

Writes one catalog YAML per product family (each well under the 500-record import limit)
and ``SUMMARY.md`` listing what was built, the prices used and what was skipped and why.
Every catalog only inserts new records; anything already on the site is declared in
``external_links`` and never updated.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from . import fixtures, others, price_list
from .common import Snapshot, catalog, declare_externals, schema, write_yaml

HEADER = (
	"Catalog expansion ({kind}) generated by tools/catalog_expansion from the live site and the\n"
	"{price_list} price list. Only inserts new records; existing records are external links.\n"
	"Review engineering values before ordering; prices follow the price list."
)


def build(snapshot_dir, price_list_path, out):
	snap = Snapshot(snapshot_dir)
	prices = price_list.read(price_list_path)
	lines = price_list.fixture_lines(prices)
	schema_ = schema()
	out = Path(out)
	out.mkdir(parents=True, exist_ok=True)
	for old in out.glob("*.yaml"):
		old.unlink()
	notes, summary = [], []
	header = dict(price_list=Path(price_list_path).name)

	families = sorted({line.family for line in lines})
	for family in families:
		result = fixtures.build_family(snap, lines, family, notes)
		if not result or not result["templates"]:
			continue
		external, missing = declare_externals(result["records"], schema_, snap)
		for doctype, name in missing:
			notes.append(f"{family}: links to {doctype} {name}, which is not on the site")
		data = catalog(
			"fixture",
			result["series"],
			result["records"],
			external,
			HEADER.format(kind=f"linear fixtures, {result['name']}", **header),
		)
		write_yaml(out / f"fixture_{family.lower()}.yaml", data)
		summary.append(
			(
				"Linear fixture",
				result["name"],
				result["templates"],
				{k: v for k, v in result["price"]["base"].items()},
				result["price"],
			)
		)

	for item in others.build_all(snap, prices, notes):
		external, missing = declare_externals(item["records"], schema_, snap, item.get("extra_external"))
		for doctype, name in missing:
			notes.append(f"{item['slug']}: links to {doctype} {name}, which is not on the site")
		data = catalog(
			item["product_type"],
			item["series"],
			item["records"],
			external,
			HEADER.format(kind=item["label"], **header),
		)
		write_yaml(out / f"{item['slug']}.yaml", data)
		summary.append((item["kind"], item["label"], item["templates"], item.get("prices", {}), None))

	write_summary(out / "SUMMARY.md", summary, notes, Path(price_list_path).name)
	return summary, notes


def write_summary(path, summary, notes, price_list_name):
	lines = [
		"# Catalog expansion summary",
		"",
		f"Generated from the live site snapshot and `{price_list_name}`. One catalog per family;",
		"import each with the Catalog Builder (Check, then Import) or the `catalog_builder` API.",
		"",
		"| Kind | Product | New templates | Price basis |",
		"| --- | --- | --- | --- |",
	]
	total = 0
	for kind, name, templates, prices, detail in summary:
		total += len(templates)
		basis = ", ".join(f"{k} ${v:.2f}" for k, v in prices.items()) if prices else ""
		if detail:
			adders = [f"{k} +${v:.2f}" for k, v in {**detail["lens"], **detail["mount"]}.items() if v]
			if adders:
				basis += " · adders/ft: " + ", ".join(adders)
		lines.append(f"| {kind} | {name} | {', '.join(templates)} | {basis} |")
	lines += ["", f"**{total} new templates.**", "", "## Notes", ""]
	lines += [f"- {note}" for note in notes] or ["- None"]
	Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument("--snapshot", required=True)
	parser.add_argument("--price-list", required=True)
	parser.add_argument("--out", default=str(Path(__file__).parent / "catalogs"))
	args = parser.parse_args()
	summary, notes = build(args.snapshot, args.price_list, args.out)
	print(f"{sum(len(s[2]) for s in summary)} templates in {len(summary)} catalogs; {len(notes)} notes")
